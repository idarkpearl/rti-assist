-- Flyway Migration V1: Initial Database Schema for RTI Assist
-- Tables: users, authorities, cases, deadlines, appeals, documents, reminder_log

CREATE TABLE IF NOT EXISTS users (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    email VARCHAR(255) NOT NULL UNIQUE,
    role VARCHAR(64) DEFAULT 'citizen',
    password VARCHAR(255) DEFAULT '',
    has_password BOOLEAN DEFAULT FALSE,
    email_verified BOOLEAN DEFAULT TRUE,
    created_at VARCHAR(64),
    updated_at VARCHAR(64)
);

CREATE TABLE IF NOT EXISTS authorities (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    code VARCHAR(64),
    ministry VARCHAR(255),
    department VARCHAR(255),
    level VARCHAR(64),
    jurisdiction VARCHAR(128),
    category_tags TEXT,
    portal_url VARCHAR(512),
    application_fee VARCHAR(64),
    payment_modes TEXT,
    pio_name VARCHAR(255),
    pio_designation VARCHAR(255),
    pio_email VARCHAR(255),
    pio_phone VARCHAR(64),
    pio_address TEXT,
    faa_name VARCHAR(255),
    faa_designation VARCHAR(255),
    faa_email VARCHAR(255),
    faa_phone VARCHAR(64),
    faa_address TEXT,
    created_at VARCHAR(64)
);

CREATE TABLE IF NOT EXISTS cases (
    id VARCHAR(64) PRIMARY KEY,
    user_id VARCHAR(64) REFERENCES users(id),
    tracking_number VARCHAR(128),
    title VARCHAR(512) NOT NULL,
    subject_category VARCHAR(255),
    summary TEXT,
    description TEXT,
    queries TEXT,
    applicant_name VARCHAR(255),
    applicant_email VARCHAR(255),
    applicant_phone VARCHAR(64),
    applicant_address TEXT,
    authority_id VARCHAR(64) REFERENCES authorities(id),
    status VARCHAR(64) DEFAULT 'submitted',
    is_life_and_liberty BOOLEAN DEFAULT FALSE,
    filing_date VARCHAR(64),
    submission_mode VARCHAR(64) DEFAULT 'online_portal',
    fee_paid VARCHAR(64) DEFAULT '10',
    payment_reference VARCHAR(255),
    tags TEXT,
    pio_response_summary TEXT,
    pio_response_date VARCHAR(64),
    created_at VARCHAR(64),
    updated_at VARCHAR(64)
);

CREATE TABLE IF NOT EXISTS deadlines (
    id VARCHAR(64) PRIMARY KEY,
    case_id VARCHAR(64) NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
    title VARCHAR(255),
    type VARCHAR(64),
    due_date VARCHAR(64),
    calculated_days INTEGER,
    days_remaining INTEGER,
    status VARCHAR(64) DEFAULT 'pending',
    is_life_and_liberty BOOLEAN DEFAULT FALSE,
    act_section_reference VARCHAR(128) DEFAULT 'RTI Act Sec 7(1)',
    notes TEXT,
    created_at VARCHAR(64),
    completed_at VARCHAR(64),
    updated_at VARCHAR(64)
);

CREATE TABLE IF NOT EXISTS appeals (
    id VARCHAR(64) PRIMARY KEY,
    case_id VARCHAR(64) NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
    type VARCHAR(64) DEFAULT 'first_appeal',
    appeal_number VARCHAR(128),
    authority_id VARCHAR(64),
    authority_name VARCHAR(255),
    ground_of_appeal VARCHAR(128) DEFAULT 'no_response',
    grounds_summary TEXT,
    draft_content TEXT,
    status VARCHAR(64) DEFAULT 'ready_to_send',
    created_at VARCHAR(64),
    updated_at VARCHAR(64)
);

CREATE TABLE IF NOT EXISTS documents (
    id VARCHAR(64) PRIMARY KEY,
    case_id VARCHAR(64) NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
    filename VARCHAR(255) NOT NULL,
    content_type VARCHAR(128),
    storage_path VARCHAR(512),
    uploaded_at VARCHAR(64),
    kind VARCHAR(64) DEFAULT 'attachment',
    file_size BIGINT
);

CREATE TABLE IF NOT EXISTS reminder_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id VARCHAR(64) NOT NULL REFERENCES cases(id) ON DELETE CASCADE,
    reminder_type VARCHAR(64) NOT NULL,
    sent_at VARCHAR(64) NOT NULL,
    CONSTRAINT uk_case_reminder UNIQUE (case_id, reminder_type)
);
