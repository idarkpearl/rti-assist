package org.rtiassist.service;

import com.lowagie.text.*;
import com.lowagie.text.pdf.PdfWriter;
import org.rtiassist.model.Appeal;
import org.rtiassist.model.Authority;
import org.rtiassist.model.CaseItem;
import org.springframework.stereotype.Service;

import java.io.ByteArrayOutputStream;
import java.util.List;

@Service
public class PdfExportService {

    private static final Font TITLE_FONT = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 15);
    private static final Font SUBTITLE_FONT = FontFactory.getFont(FontFactory.HELVETICA_BOLD, 11);
    private static final Font BODY_FONT = FontFactory.getFont(FontFactory.HELVETICA, 10.5f);
    private static final Font SMALL_FONT = FontFactory.getFont(FontFactory.HELVETICA_OBLIQUE, 9);

    public byte[] generateCasePdf(CaseItem caseItem) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        Document doc = new Document(PageSize.A4, 50, 50, 50, 50);
        PdfWriter.getInstance(doc, out);
        doc.open();

        Paragraph header = new Paragraph("APPLICATION UNDER SECTION 6(1) OF THE RIGHT TO INFORMATION ACT, 2005", TITLE_FONT);
        header.setAlignment(Element.ALIGN_CENTER);
        header.setSpacingAfter(14);
        doc.add(header);

        Authority auth = caseItem.getAuthority();
        String pioLine = (auth != null && auth.getPio() != null)
                ? auth.getPio().getDesignation() + "\n" + auth.getName() + "\n" + safe(auth.getPio().getAddress())
                : "The Public Information Officer (PIO)\nConcerned Public Authority";

        doc.add(new Paragraph("To,\n" + pioLine, BODY_FONT));
        doc.add(new Paragraph("\nTracking / Reference No.: " + safe(caseItem.getTrackingNumber()), SUBTITLE_FONT));
        doc.add(new Paragraph("Filing Date: " + safe(caseItem.getFilingDate()), BODY_FONT));
        doc.add(new Paragraph("Subject: " + safe(caseItem.getTitle()), SUBTITLE_FONT));

        if (Boolean.TRUE.equals(caseItem.getIsLifeAndLiberty())) {
            doc.add(new Paragraph("URGENT: Concerns Life & Liberty under Section 7(1) Proviso (48-hour mandatory reply).", SUBTITLE_FONT));
        }

        doc.add(new Paragraph("\nSir / Madam,\n", BODY_FONT));
        doc.add(new Paragraph(safe(caseItem.getDescription()), BODY_FONT));

        List<String> queries = caseItem.getQueries();
        if (queries != null && !queries.isEmpty()) {
            doc.add(new Paragraph("\nParticulars of Information Requested:", SUBTITLE_FONT));
            int i = 1;
            for (String q : queries) {
                Paragraph p = new Paragraph(i++ + ". " + q, BODY_FONT);
                p.setSpacingBefore(4);
                doc.add(p);
            }
        }

        if (caseItem.getApplicant() != null) {
            doc.add(new Paragraph("\nApplicant Particulars:", SUBTITLE_FONT));
            doc.add(new Paragraph("Name: " + safe(caseItem.getApplicant().getFullName()), BODY_FONT));
            doc.add(new Paragraph("Email: " + safe(caseItem.getApplicant().getEmail()), BODY_FONT));
            if (caseItem.getApplicant().getPhone() != null) {
                doc.add(new Paragraph("Phone: " + caseItem.getApplicant().getPhone(), BODY_FONT));
            }
            if (caseItem.getApplicant().getAddress() != null) {
                doc.add(new Paragraph("Address: " + caseItem.getApplicant().getAddress(), BODY_FONT));
            }
        }

        doc.add(new Paragraph("\nGenerated by RTI Assist — Statutory Compliance Engine (RTI Act, 2005)", SMALL_FONT));
        doc.close();
        return out.toByteArray();
    }

    public byte[] generateAppealPdf(Appeal appeal, CaseItem parentCase) {
        ByteArrayOutputStream out = new ByteArrayOutputStream();
        Document doc = new Document(PageSize.A4, 50, 50, 50, 50);
        PdfWriter.getInstance(doc, out);
        doc.open();

        boolean isSecond = "second_appeal".equalsIgnoreCase(appeal.getType());
        String heading = isSecond
                ? "SECOND APPEAL UNDER SECTION 19(3) OF THE RIGHT TO INFORMATION ACT, 2005"
                : "FIRST APPEAL UNDER SECTION 19(1) OF THE RIGHT TO INFORMATION ACT, 2005";

        Paragraph header = new Paragraph(heading, TITLE_FONT);
        header.setAlignment(Element.ALIGN_CENTER);
        header.setSpacingAfter(14);
        doc.add(header);

        doc.add(new Paragraph("Appeal Reference No.: " + safe(appeal.getAppealNumber()), SUBTITLE_FONT));
        doc.add(new Paragraph("Authority: " + safe(appeal.getAuthorityName()), BODY_FONT));
        if (appeal.getAppellateAuthorityName() != null) {
            doc.add(new Paragraph("Appellate Authority: " + appeal.getAppellateAuthorityName()
                    + (appeal.getAppellateAuthorityDesignation() != null ? " (" + appeal.getAppellateAuthorityDesignation() + ")" : ""), BODY_FONT));
        }
        if (parentCase != null) {
            doc.add(new Paragraph("Original RTI Tracking No.: " + safe(parentCase.getTrackingNumber()), BODY_FONT));
        }

        doc.add(new Paragraph("\nGround of Appeal: " + safe(appeal.getGroundOfAppeal()), SUBTITLE_FONT));
        if (appeal.getGroundsSummary() != null) {
            doc.add(new Paragraph(appeal.getGroundsSummary(), BODY_FONT));
        }

        if (appeal.getDetailedGrounds() != null && !appeal.getDetailedGrounds().isEmpty()) {
            doc.add(new Paragraph("\nDetailed Grounds:", SUBTITLE_FONT));
            int i = 1;
            for (String g : appeal.getDetailedGrounds()) {
                doc.add(new Paragraph(i++ + ". " + g, BODY_FONT));
            }
        }

        if (appeal.getReliefSought() != null) {
            doc.add(new Paragraph("\nPrayer / Relief Sought:", SUBTITLE_FONT));
            doc.add(new Paragraph(appeal.getReliefSought(), BODY_FONT));
        }

        if (appeal.getDraftContent() != null && !appeal.getDraftContent().isBlank()) {
            doc.add(new Paragraph("\nFull Appeal Petition:", SUBTITLE_FONT));
            doc.add(new Paragraph(appeal.getDraftContent(), BODY_FONT));
        }

        doc.add(new Paragraph("\nGenerated by RTI Assist — Statutory Compliance Engine (RTI Act, 2005)", SMALL_FONT));
        doc.close();
        return out.toByteArray();
    }

    private String safe(String s) {
        return s != null ? s : "N/A";
    }
}
